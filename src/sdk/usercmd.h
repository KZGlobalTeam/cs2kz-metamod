#pragma once
#include "common.h"
#include "cs_usercmd.pb.h"
#include "cinbuttonstate.h"
class CSGOUserCmdPB;

class CUserCmdBase
{
public:
	int cmdNum;
	uint8_t unk[4];

	virtual ~CUserCmdBase();

private:
	virtual void unk0();
	virtual void unk1();
	virtual void unk2();
	virtual void unk3();
	virtual void unk4();
	virtual void unk5();
	virtual void unk6();
};

template<typename T>
class CUserCmdBaseHost : public CUserCmdBase, public T
{
};

class CCSGOUserCmd : public CUserCmdBaseHost<CSGOUserCmdPB>
{
public:
	CInButtonState buttonstates;

	// Not part of the player message. Defaults to -1 and the server only ever copies it.
	int32_t unknown;
};

// Set by the server on every command it decodes. Any bit except USERCMD_SUBSTITUTE also sets 0x20 in the base cmd_flags.
enum UserCmdFlags : uint32_t
{
	USERCMD_SUBSTITUTE = 0x1, // Generated by the server for a client that sent nothing in time.
	USERCMD_BAD_ATTACK1_HISTORY_INDEX = 0x2,
	USERCMD_BAD_ATTACK2_HISTORY_INDEX = 0x4,
	USERCMD_BAD_VIEWANGLES = 0x10,
	USERCMD_BAD_FORWARDMOVE = 0x20,
	USERCMD_BAD_LEFTMOVE = 0x40,
	USERCMD_BAD_UPMOVE = 0x80,
	USERCMD_BAD_HISTORY_VIEWANGLES = 0x200,
	USERCMD_BAD_HISTORY_PLAYER_TICK_FRACTION = 0x800,
	USERCMD_BAD_HISTORY_RENDER_TICK_FRACTION = 0x2000,
	USERCMD_BAD_SHOOT_POSITION = 0x4000,
	USERCMD_BAD_TARGET_HEAD_POS = 0x8000,
	USERCMD_BAD_TARGET_ABS_POS = 0x10000,
	USERCMD_BAD_TARGET_ABS_ANG = 0x20000,
	USERCMD_BAD_CL_INTERP = 0x40000,
	USERCMD_BAD_SV_INTERP0 = 0x80000,
	USERCMD_BAD_SV_INTERP1 = 0x100000,
	USERCMD_BAD_PLAYER_INTERP = 0x200000,
	USERCMD_BAD_SUBTICK_WHEN = 0x400000,
	USERCMD_BAD_SUBTICK_ANALOG_FORWARD = 0x800000,
	USERCMD_BAD_SUBTICK_ANALOG_LEFT = 0x1000000,
	USERCMD_BAD_SUBTICK_PITCH = 0x2000000,
	USERCMD_BAD_SUBTICK_YAW = 0x4000000,
};

class CUserCmd : public CCSGOUserCmd
{
public:
	uint32_t flags;
	// Only set on late commands, to the substitute that already ran in this command's place.
	CUserCmd *substituteCmd;
	// Only set on late commands, to the on-time command this one runs right before.
	CUserCmd *onTimeCmd;

	bool IsLate() const
	{
		return onTimeCmd != nullptr;
	}
};

#ifndef _WIN32
static_assert(sizeof(CUserCmd) == 144, "Size of CUserCmd is incorrect");
#else
static_assert(sizeof(CUserCmd) == 152, "Size of CUserCmd is incorrect");
#endif
